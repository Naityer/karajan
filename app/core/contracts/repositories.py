"""Puertos de persistencia de Karajan.

Hoy hay una sola implementación —SQLite sobre `data/*.db` y `data/*.json`— y la
API la usa directamente. Eso funciona para standalone, pero deja el modo SaaS
sin sitio donde entrar: no hay ninguna frontera que un backend Postgres
multi-tenant pueda ocupar (nota "Plan de mejora", §15).

Estos Protocols son esa frontera. Describen **solo** lo que la capa de API
consume de cada almacén, así que:

- `app/platform/persistence/sqlite/` los satisface con las clases que ya
  existen (`TaskStore`, `ResourceStore`, `RoutingLayoutStore`), sin reescribir
  su lógica;
- una futura implementación Postgres tiene aquí la lista cerrada de lo que
  necesita implementar, en vez de tener que leer 90 endpoints;
- los tests pueden sustituir un almacén por un doble sin heredar de nada.

Son estructurales (`Protocol`): ninguna clase existente necesita declararlos.
Los tipos de retorno son los modelos de dominio de `app/models.py`, que no
dependen del motor de almacenamiento.
"""

from __future__ import annotations

from typing import Any, Protocol

from app.models import (
    DecisionLogEntry,
    DiscoverySource,
    KarajanConfig,
    Metrics,
    MetricsHistory,
    ResourceCreateRequest,
    ResourceGroup,
    ResourceGroupCreateRequest,
    ResourceGroupUpdateRequest,
    ResourceItem,
    ResourceOperationResult,
    ResourceUpdateRequest,
    RoutingLayout,
    TaskRecord,
    TaskStatus,
)


class TaskRepository(Protocol):
    """Tareas, clasificaciones, delegaciones, runs y su telemetría."""

    # --- ciclo de vida de la tarea ---
    def save_classification(self, *args: Any, **kwargs: Any) -> TaskRecord: ...
    def save_delegation(self, *args: Any, **kwargs: Any) -> TaskRecord: ...
    def mark_status(self, task_id: str, status: TaskStatus) -> TaskRecord: ...
    def get_task(self, task_id: str) -> TaskRecord: ...
    def list_tasks(self, limit: int | None = None, offset: int = 0) -> list[TaskRecord]: ...
    def count_tasks(self) -> int: ...
    def get_idempotency(
        self, workspace_id: str, operation_name: str, idempotency_key: str
    ) -> dict | None: ...
    def list_pending_outbox(self, limit: int = 100) -> list[dict]: ...
    def mark_outbox_delivered(self, event_id: str) -> None: ...
    def record_outbox_attempt(self, event_id: str) -> None: ...

    # --- trazas ---
    def add_decisions(self, decisions: list[DecisionLogEntry]) -> None: ...
    def list_decisions(self, task_id: str | None = None) -> list[DecisionLogEntry]: ...
    def list_runs(self, task_id: str) -> list[dict]: ...
    def list_run_events(self, run_id: str, limit: int = 500, offset: int = 0) -> list[dict]: ...
    def list_artifacts(self, task_id: str) -> list[dict]: ...

    # --- escritura de runs (usada por app/delegation.py, app/agent_tools/trace.py
    # y app/handoff/store.py directamente contra el store, no vía la API) ---
    # `*args`/`**kwargs`, igual que `save_classification`/`save_delegation`
    # arriba: las firmas reales varían más entre implementaciones (SQLite guarda
    # snapshots que Postgres simplifica — ver `PostgresTaskRepository`) de lo
    # que vale la pena fijar aquí un `Protocol` que ninguna implementación real
    # necesitaba antes de que estos tres módulos empezaran a llamarlos.
    def open_run(self, *args: Any, **kwargs: Any) -> str: ...
    def close_run(self, *args: Any, **kwargs: Any) -> None: ...
    def record_run(self, *args: Any, **kwargs: Any) -> None: ...
    def record_run_event(self, *args: Any, **kwargs: Any) -> str: ...
    def record_artifact(self, *args: Any, **kwargs: Any) -> str: ...

    # --- lectura analítica que vive en el mismo almacén ---
    def metrics(self) -> Metrics: ...
    def metrics_history(self, limit: int = 200) -> MetricsHistory: ...
    def agent_performance(self) -> list[dict]: ...
    def search_tasks(self, query: str, limit: int = 20) -> list[dict]: ...


class RoutingRepository(Protocol):
    """Arquitectura de decisión: entidades, grupos Prio y su disposición."""

    def load(self) -> RoutingLayout: ...
    def save(self, layout: RoutingLayout) -> RoutingLayout: ...


class ConfigRepository(Protocol):
    """Configuración activa.

    Es un puerto y no una variable porque `PUT /config` y el asistente de
    puesta en marcha la **reemplazan** en caliente: cualquier módulo que se
    quedara con una copia leería configuración obsoleta en cuanto el usuario
    la cambiase.
    """

    def load(self) -> KarajanConfig: ...
    def save(self, config: KarajanConfig) -> KarajanConfig: ...


class ResourceRepository(Protocol):
    """Biblioteca de Inspiration: recursos, grupos, fuentes y operaciones."""

    # --- recursos ---
    def upsert(self, item: ResourceItem) -> ResourceItem: ...
    def create(self, request: ResourceCreateRequest) -> ResourceItem: ...
    def get(self, resource_id: str) -> ResourceItem: ...
    def find_by_repo_url(self, repo_url: str) -> ResourceItem | None: ...
    def update_resource(self, resource_id: str, request: ResourceUpdateRequest) -> ResourceItem: ...
    def list_resources(self, *args: Any, **kwargs: Any) -> list[ResourceItem]: ...
    def list_all_resources(self, *args: Any, **kwargs: Any) -> list[ResourceItem]: ...
    def list_children(self, parent_resource_id: str, *, include_inactive: bool = False) -> list[ResourceItem]: ...
    def search(self, query: str, *, limit: int = 50) -> list[ResourceItem]: ...
    def recommendation_candidates(self, query: str, *, limit: int = 100) -> list[ResourceItem]: ...
    def set_visibility(self, resource_id: str, agent_ids: list[str]) -> ResourceItem: ...

    # --- grupos ---
    def ensure_default_groups(self) -> list[ResourceGroup]: ...
    def list_groups(self) -> list[ResourceGroup]: ...
    def create_group(self, request: ResourceGroupCreateRequest) -> ResourceGroup: ...
    def update_group(self, group_id: str, request: ResourceGroupUpdateRequest) -> ResourceGroup: ...
    def delete_group(self, group_id: str, *, move_to_id: str | None = None) -> None: ...
    def assign_groups(self, assignments: dict[str, str | None]) -> list[ResourceGroup]: ...

    # --- descubrimiento y preferencias ---
    def upsert_discovery_source(self, source: DiscoverySource) -> DiscoverySource: ...
    def list_discovery_sources(self) -> list[DiscoverySource]: ...
    def migrate_radar_profiles(self) -> list[DiscoverySource]: ...
    def get_preference(self, key: str, default: object = None) -> object: ...
    def set_preference(self, key: str, value: object) -> object: ...

    # --- historial de operaciones ---
    def record_operation(self, *args: Any, **kwargs: Any) -> ResourceOperationResult: ...
    def list_operations(self, resource_id: str | None = None, *, limit: int = 100) -> list[ResourceOperationResult]: ...


class AnalyticsRepository(Protocol):
    """Analítica agregada (DuckDB sobre los mismos datos).

    Separada de `TaskRepository` porque su implementación es opcional: si
    DuckDB no está disponible el endpoint responde 503 en vez de romper la
    aplicación entera.
    """

    def dashboard(self, days: int = 30) -> dict: ...
    def available(self) -> bool: ...
